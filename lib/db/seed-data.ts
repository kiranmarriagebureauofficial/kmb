// Helper to calculate date offsets relative to today (2026-11-06)
const getDateOffset = (daysAgo: number): string => {
  const base = new Date('2026-11-06T12:00:00Z').getTime();
  const d = new Date(base - daysAgo * 86400000);
  return d.toISOString().split('T')[0];
};

const getTimestampOffset = (daysAgo: number, hoursAgo = 2): string => {
  const base = new Date('2026-11-06T12:00:00Z').getTime();
  const d = new Date(base - (daysAgo * 86400000 + hoursAgo * 3600000));
  return d.toISOString();
};

